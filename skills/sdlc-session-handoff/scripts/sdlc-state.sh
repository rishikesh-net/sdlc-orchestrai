#!/usr/bin/env bash
# sdlc-state.sh - shared, client-neutral project memory (state.json + HANDOFF.md + codebase-map staleness).
#
# Commands:
#   init                       create .sdlc/state.json, HANDOFF.md, memory/ files if missing
#   resume                     print handoff, staleness vs HEAD, changed files, codebase-map status
#   checkpoint [options]       record progress (see below); regenerates HANDOFF.md
#   render                     regenerate HANDOFF.md from state.json
#   validate                   check state.json structure and enums
#   map-status                 is the codebase map current? list changed paths since its stamp
#   map-stamp                  stamp the codebase map with the current commit
#
# checkpoint options:
#   --client NAME      claude-code | copilot | cursor | opencode | antigravity (or env SDLC_CLIENT)
#   --feature SLUG     required
#   --phase PHASE      requirements design threat-model backlog issues build security-review done
#   --gate NAME=STATUS repeatable; STATUS: pending | in-review | approved | skipped
#   --artifact PATH    repeatable
#   --next "TEXT"      exact next step (written so a different client can execute it)
#   --question "TEXT"  repeatable; add an open question
#   --close-question "TEXT"  repeatable; remove an open question (exact text)
#   --slice SLUG       scope --gate entries to one requirements slice (gate names become NAME:SLUG) and record the
#                      slice file's hash, so 'resume' can flag the slice if it changes after approval
#   --branch NAME      working branch
#   --note "TEXT"      short note (last five kept)
set -euo pipefail

command -v jq >/dev/null 2>&1 || { echo "ERROR: jq is required" >&2; exit 2; }
ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
SDLC="$ROOT/.sdlc"; STATE="$SDLC/state.json"; HANDOFF="$SDLC/HANDOFF.md"
MEM="$SDLC/memory"; MAP="$MEM/codebase-map.md"; GRAPH="$MEM/graph.jsonl"
TEMPLATES="$ROOT/skills/sdlc-session-handoff/templates"
PHASES="requirements design threat-model backlog issues build security-review done"
GATE_STATUS="pending in-review approved skipped"
REQ_BASE="$ROOT/${SDLC_REQ_DIR:-docs/requirements}"

die() { echo "ERROR: $*" >&2; exit 2; }
in_list() { local x="$1"; shift; for i in $*; do [[ "$i" == "$x" ]] && return 0; done; return 1; }
hash_file() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -c1-16
  elif command -v shasum >/dev/null 2>&1; then shasum -a 256 "$1" | cut -c1-16
  else openssl dgst -sha256 "$1" | awk '{print substr($NF,1,16)}'; fi
}
find_slice_file() { # feature slug
  local f; for f in "$REQ_BASE/$1"/slices/*-"$2".md "$REQ_BASE/$1"/slices/"$2".md; do [[ -f "$f" ]] && { echo "$f"; return 0; }; done; return 1
}
head_sha() { git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo "none"; }
is_dirty() { # ignores .sdlc/ (checkpoints themselves modify it)
  [[ -n "$(git -C "$ROOT" status --porcelain 2>/dev/null | grep -v ' \.sdlc/' | head -1 || true)" ]]
}

cmd_init() {
  mkdir -p "$MEM" "$SDLC/reports"
  [[ -f "$STATE" ]] || echo '{"schema_version":1,"features":{}}' | jq . > "$STATE"
  [[ -f "$GRAPH" ]] || : > "$GRAPH"
  if [[ ! -f "$MAP" ]]; then
    if [[ -f "$TEMPLATES/codebase-map.md.tmpl" ]]; then cp "$TEMPLATES/codebase-map.md.tmpl" "$MAP"
    else printf '<!-- map-sha: UNSET -->\n<!-- map-date: UNSET -->\n# Codebase map\n' > "$MAP"; fi
  fi
  cmd_render
  echo "Initialized shared memory in .sdlc/ (state.json, HANDOFF.md, memory/)."
}

cmd_render() {
  [[ -f "$STATE" ]] || die "no state.json (run: sdlc-state.sh init)"
  local out; out="$(mktemp)"
  {
    echo "# Handoff"; echo
    echo "_Generated by \`sdlc-state.sh render\` from \`.sdlc/state.json\`. Do not edit by hand._"; echo
    jq -r '
      "Last updated: \(.updated_at // "never") by \(.updated_by // "unknown") at commit \(.repo_sha // "n/a")\(if .repo_dirty then " (code had uncommitted changes)" else "" end)\n",
      ( if ((.features // {}) | length) == 0 then "(No features recorded yet.)" else
        ( .features | to_entries[] |
          "## \(.key) - phase: \(.value.phase // "n/a")\n",
          "**Next action:** \(.value.next_action // "none recorded")\n",
          ( if ((.value.gates // {}) | length) > 0 then
              "| Gate | Status |", "|---|---|",
              ( .value.gates | to_entries[] | "| \(.key) | \(.value) |" ), ""
            else empty end ),
          ( if ((.value.open_questions // []) | length) > 0 then
              "**Open questions**", ( .value.open_questions[] | "- " + . ), ""
            else empty end ),
          ( if ((.value.artifacts // []) | length) > 0 then
              "**Artifacts**", ( .value.artifacts[] | "- `" + . + "`" ), ""
            else empty end ),
          ( if (.value.branch // null) != null then "**Branch:** `\(.value.branch)`\n" else empty end ),
          ( if ((.value.notes // []) | length) > 0 then
              "**Recent notes**", ( .value.notes[] | "- \(.at) (\(.by)): \(.text)" ), ""
            else empty end )
        ) end )' "$STATE"
  } > "$out"
  mv "$out" "$HANDOFF"; chmod 644 "$HANDOFF"
}

cmd_checkpoint() {
  [[ -f "$STATE" ]] || cmd_init >/dev/null
  local client="${SDLC_CLIENT:-unknown}" feature="" phase="" next="" branch="" note="" slice=""
  local gates='{}' arts='[]' qs='[]' closeqs='[]'
  while [[ $# -gt 0 ]]; do
    [[ $# -ge 2 ]] || die "option $1 needs a value"
    case "$1" in
      --client) client="$2" ;;
      --feature) feature="$2" ;;
      --phase) phase="$2" ;;
      --gate)
        [[ "$2" == *=* ]] || die "--gate expects NAME=STATUS"
        local gk="${2%%=*}" gv="${2#*=}"
        in_list "$gv" $GATE_STATUS || die "gate status must be one of: $GATE_STATUS"
        gates=$(jq -c --arg k "$gk" --arg v "$gv" '. + {($k):$v}' <<<"$gates") ;;
      --artifact) arts=$(jq -c --arg v "$2" '. + [$v]' <<<"$arts") ;;
      --next) next="$2" ;;
      --question) qs=$(jq -c --arg v "$2" '. + [$v]' <<<"$qs") ;;
      --close-question) closeqs=$(jq -c --arg v "$2" '. + [$v]' <<<"$closeqs") ;;
      --branch) branch="$2" ;;
      --slice) slice="$2" ;;
      --note) note="$2" ;;
      *) die "unknown option: $1" ;;
    esac
    shift 2
  done
  [[ -n "$feature" ]] || die "--feature is required"
  [[ "$feature" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]] || die "--feature must be a slug (letters, digits, . _ -)"
  [[ -z "$phase" ]] || in_list "$phase" $PHASES || die "phase must be one of: $PHASES"
  local slice_hash=""
  if [[ -n "$slice" ]]; then
    [[ "$slice" =~ ^[a-z0-9][a-z0-9-]*$ ]] || die "--slice must be a lowercase slug (a-z, 0-9, -)"
    local sf; sf="$(find_slice_file "$feature" "$slice")" || die "slice '$slice' not found under ${REQ_BASE#"$ROOT"/}/$feature/slices/"
    slice_hash="$(hash_file "$sf")"
    gates=$(jq -c --arg s "$slice" 'with_entries(.key = (.key + ":" + $s))' <<<"$gates")
  fi

  local now sha dirty tmp; now="$(date -u +%Y-%m-%dT%H:%M:%SZ)"; sha="$(head_sha)"
  if is_dirty; then dirty=true; else dirty=false; fi
  tmp="$(mktemp)"
  jq --arg f "$feature" --arg client "$client" --arg now "$now" --arg sha "$sha" --argjson dirty "$dirty" \
     --arg phase "$phase" --arg next "$next" --arg branch "$branch" --arg note "$note" --arg slice "$slice" --arg shash "$slice_hash" \
     --argjson gates "$gates" --argjson arts "$arts" --argjson qs "$qs" --argjson closeqs "$closeqs" '
    .updated_by = $client | .updated_at = $now | .repo_sha = $sha | .repo_dirty = $dirty
    | .features = (.features // {})
    | .features[$f] = (
        (.features[$f] // {phase:"requirements", gates:{}, artifacts:[], open_questions:[], notes:[]})
        | .updated_by = $client | .updated_at = $now
        | (if $phase != "" then .phase = $phase else . end)
        | (if $next != "" then .next_action = $next else . end)
        | (if $branch != "" then .branch = $branch else . end)
        | (if $slice != "" then .slice_hashes = ((.slice_hashes // {}) + {($slice): $shash}) else . end)
        | .gates = ((.gates // {}) + $gates)
        | .artifacts = (((.artifacts // []) + $arts) | unique)
        | .open_questions = ((((.open_questions // []) + $qs) | unique) - $closeqs)
        | (if $note != "" then .notes = (((.notes // []) + [{at:$now, by:$client, text:$note}]) | .[-5:]) else . end)
      )' "$STATE" > "$tmp" && mv "$tmp" "$STATE" && chmod 644 "$STATE"
  cmd_render
  echo "Checkpoint saved: feature=$feature phase=${phase:-unchanged} by=$client commit=$sha dirty=$dirty"
  echo "Commit the .sdlc/ changes so other clients and machines can resume."
}

cmd_validate() {
  [[ -f "$STATE" ]] || die "no state.json"
  if jq -e --arg phases "$PHASES" --arg gs "$GATE_STATUS" '
      (.schema_version == 1) and ((.features // {}) | type == "object")
      and ([ (.features // {})[] | (.phase // "requirements") ] | all(. as $p | ($phases | split(" ") | index($p)) != null))
      and ([ (.features // {})[] | (.gates // {}) | to_entries[] | .value ] | all(. as $g | ($gs | split(" ") | index($g)) != null))
    ' "$STATE" >/dev/null 2>&1; then echo "state.json: OK"; else echo "state.json: INVALID (check schema_version, phases, gate statuses)" >&2; return 1; fi
}

cmd_map_status() {
  if [[ ! -f "$MAP" ]]; then echo "map: missing (run init, then build it per references/codebase-map-guide.md)"; return 0; fi
  local sha; sha="$(sed -nE 's/.*map-sha:[[:space:]]*([0-9a-zA-Z]+).*/\1/p' "$MAP" | head -1)"
  if [[ -z "$sha" || "$sha" == "UNSET" ]]; then echo "map: not built yet (build it, then run map-stamp)"; return 0; fi
  if ! git -C "$ROOT" cat-file -e "${sha}^{commit}" 2>/dev/null; then
    echo "map: stamped commit $sha not found locally; verify the map or rebuild affected sections"; return 0; fi
  if [[ "$(git -C "$ROOT" rev-parse "$sha")" == "$(git -C "$ROOT" rev-parse HEAD)" ]]; then
    echo "map: current ($sha)"; return 0; fi
  local n; n="$(git -C "$ROOT" diff --name-only "$sha"..HEAD | grep -vc '^\.sdlc/' || true)"
  echo "map: STALE (stamped $sha, HEAD $(head_sha)); $n files changed. Re-read only these paths:"
  git -C "$ROOT" diff --name-only "$sha"..HEAD | grep -v '^\.sdlc/' | head -60 || true
}

cmd_map_stamp() {
  [[ -f "$MAP" ]] || die "no codebase map to stamp (run init and build the map)"
  local sha today tmp; sha="$(head_sha)"; today="$(date -u +%Y-%m-%d)"; tmp="$(mktemp)"
  if grep -q 'map-sha:' "$MAP"; then
    sed -E "s/map-sha:[[:space:]]*[0-9a-zA-Z]+/map-sha: $sha/; s/map-date:[[:space:]]*[0-9A-Za-z-]+/map-date: $today/" "$MAP" > "$tmp"
  else
    { printf '<!-- map-sha: %s -->\n<!-- map-date: %s -->\n' "$sha" "$today"; cat "$MAP"; } > "$tmp"
  fi
  mv "$tmp" "$MAP"; chmod 644 "$MAP"; echo "Codebase map stamped at $sha ($today)."
}

cmd_resume() {
  if [[ ! -f "$STATE" ]]; then
    echo "== SDLC resume =="; echo "No shared state yet. Run: sdlc-state.sh init (first session: also build the codebase map)."; return 0
  fi
  local head st_sha by at; head="$(head_sha)"
  st_sha="$(jq -r '.repo_sha // ""' "$STATE")"; by="$(jq -r '.updated_by // "unknown"' "$STATE")"; at="$(jq -r '.updated_at // "never"' "$STATE")"
  echo "== SDLC resume =="
  echo "HEAD: $head | state recorded at commit: ${st_sha:-n/a} | last writer: $by | at: $at"
  if is_dirty; then echo "NOTE: working tree has uncommitted code changes (run git status before assuming a clean base)."; fi
  if [[ -n "$st_sha" && "$st_sha" != "none" && "$st_sha" != "$head" ]]; then
    if git -C "$ROOT" cat-file -e "${st_sha}^{commit}" 2>/dev/null; then
      echo "Commits since last checkpoint: $(git -C "$ROOT" rev-list --count "$st_sha"..HEAD 2>/dev/null || echo '?')"
      echo "Files changed since last checkpoint (first 40):"
      git -C "$ROOT" diff --name-only "$st_sha"..HEAD | grep -v '^\.sdlc/' | head -40 | sed 's/^/  /' || true
    else
      echo "WARN: recorded commit $st_sha not found locally (fetch, or you are on a different branch). Treat state as unverified."
    fi
  else
    echo "Repo has not changed since the last checkpoint."
  fi
  # requirement slices whose content changed after they were checkpointed
  local feat slug h f cur nstale=0
  while IFS=$'\t' read -r feat slug h; do
    [[ -n "$feat" ]] || continue
    if f="$(find_slice_file "$feat" "$slug")"; then cur="$(hash_file "$f")"
      if [[ "$cur" != "$h" ]]; then echo "STALE SLICE: $feat/$slug changed since it was checkpointed; re-review its design and backlog before relying on approvals."; nstale=$((nstale+1)); fi
    else echo "MISSING SLICE: $feat/$slug (file no longer exists)"; nstale=$((nstale+1)); fi
  done < <(jq -r '.features | to_entries[] | .key as $f | (.value.slice_hashes // {}) | to_entries[] | "\($f)\t\(.key)\t\(.value)"' "$STATE")
  echo; [[ -f "$HANDOFF" ]] || cmd_render; cat "$HANDOFF"
  echo; echo "== Codebase map =="; cmd_map_status
  echo; echo "Next: continue from the next action above. Do not redo approved gates; verify their artifacts still exist."
}

CMD="${1:-}"; shift || true
case "$CMD" in
  init) cmd_init ;;
  resume) cmd_resume ;;
  checkpoint) cmd_checkpoint "$@" ;;
  render) cmd_render ;;
  validate) cmd_validate ;;
  map-status) cmd_map_status ;;
  map-stamp) cmd_map_stamp ;;
  -h|--help|help|"") sed -n '2,29p' "$0" | sed 's/^# \{0,1\}//'; [[ -n "$CMD" ]] || exit 2 ;;
  *) die "unknown command: $CMD (try --help)" ;;
esac
